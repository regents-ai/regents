defmodule RegentsWeb.Endpoint do
  use Phoenix.Endpoint, otp_app: :regents

  # A connected mount reads the cookie the socket handshake carried, so the
  # transport must decode it with the same options the request plug runs with.
  @session_options {Application, :fetch_env!, [:regents, :session_options]}

  # A stylesheet, an icon or an image may be opened directly, and the browser
  # then reads it as a page. These say what a page from this address may do,
  # which is nothing.
  @static_headers %{
    "content-security-policy" => "default-src 'none'; frame-ancestors 'none'",
    "x-content-type-options" => "nosniff",
    "x-frame-options" => "DENY",
    "referrer-policy" => "no-referrer"
  }

  # Chrome's WebMCP origin trial, issued to https://regents.sh and valid until
  # 30 Mar 2027. The token is public; Chrome ignores it on any other host.
  @webmcp_origin_trial "AmQTY8hPv9mTZTHeJKyu3FofvOMuRBSdSVDAUkj6+RB4Dds1KtJTsvi5WsbR6QTuinMfsJO5yngUcA+aq93BhAoAAABKeyJvcmlnaW4iOiJodHRwczovL3JlZ2VudHMuc2g6NDQzIiwiZmVhdHVyZSI6IldlYk1DUCIsImV4cGlyeSI6MTgwNjM2NDgwMH0="

  socket "/live", Phoenix.LiveView.Socket,
    websocket: [connect_info: [:peer_data, :uri, session: @session_options]],
    longpoll: [connect_info: [:peer_data, :uri, session: @session_options]]

  plug RegentsWeb.Plugs.CanonicalHost
  plug RegentsWeb.Plugs.ContractHeaders

  # Serve at "/" the static files from "priv/static" directory.
  #
  # When code reloading is disabled (e.g., in production),
  # the `gzip` option is enabled to serve compressed
  # static files generated by running `phx.digest`.
  plug Plug.Static,
    at: "/",
    from: :regents,
    gzip: not code_reloading?,
    only: RegentsWeb.static_paths(),
    only_matching: RegentsWeb.digested_static_prefixes(),
    raise_on_missing_only: code_reloading?,
    headers: @static_headers

  # Code reloading can be explicitly enabled under the
  # :code_reloader configuration of your endpoint.
  if code_reloading? do
    socket "/phoenix/live_reload/socket", Phoenix.LiveReloader.Socket
    plug Phoenix.LiveReloader
    plug Phoenix.CodeReloader
  end

  plug Plug.RequestId
  # Which visit, and which kind of caller, each line of this request belongs to.
  plug RegentsWeb.VisitLog
  plug Plug.Telemetry, event_prefix: [:phoenix, :endpoint]

  # Every answer, including the Markdown and refusals the next plugs give before
  # the router, lets browser agents use the tools this site's pages register and
  # carries the origin-trial token, so Chrome knows it before reading `tools`.
  plug :allow_page_tools

  # One budget per client address, shared by the health check, the browser's visit
  # reports and every /api path, answered or not; pairing counts against its own
  # budget too, and the MCP address has its own. Every answer says what is left of
  # each; past one, 429 with Retry-After.
  plug :limit_rate

  # Before the parsers, so a body they reject on an /api path or the MCP address
  # is answered in JSON like every other API error.
  plug RegentAgentAccess.Plug,
    documents: &RegentsWeb.PublicDocuments.document/1,
    guide: "/llms.txt",
    json_prefixes: ["api", "mcp"]

  # After the error format is chosen, so a slash address is answered as any
  # address that names nothing.
  plug RegentsWeb.Plugs.NoTrailingSlash

  # The largest body the site takes is a sign-in request of a few kilobytes;
  # anything past a megabyte is refused before it is read.
  plug RegentsWeb.Plugs.Parsers,
    body_reader: {RegentsWeb.Plugs.AgentBodyReader, :read_body, []},
    parsers: [:urlencoded, :json],
    pass: ["*/*"],
    length: 1_000_000,
    json_decoder: Phoenix.json_library()

  plug Plug.MethodOverride
  plug Plug.Head
  plug RegentsWeb.Plugs.RuntimeSession
  plug RegentsWeb.Router

  defp allow_page_tools(conn, _opts) do
    conn
    |> Plug.Conn.put_resp_header("permissions-policy", "tools=(self)")
    |> Plug.Conn.put_resp_header("origin-trial", @webmcp_origin_trial)
  end

  defp limit_rate(%Plug.Conn{path_info: ["healthz"]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, rate_limit("default", 120))

  defp limit_rate(
         %Plug.Conn{method: "POST", path_info: ["api", "agents", "v1", "pair"]} = conn,
         _opts
       ) do
    conn = RegentAgentAccess.RateLimit.call(conn, rate_limit("default", 120))
    if conn.halted, do: conn, else: RegentAgentAccess.RateLimit.call(conn, rate_limit("pair", 10))
  end

  defp limit_rate(%Plug.Conn{method: "POST", path_info: ["visit-log"]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, rate_limit("default", 120))

  defp limit_rate(%Plug.Conn{path_info: ["api" | _]} = conn, _opts),
    do: RegentAgentAccess.RateLimit.call(conn, rate_limit("default", 120))

  defp limit_rate(%Plug.Conn{path_info: ["mcp" | _]} = conn, _opts),
    do: RegentsWeb.Plugs.McpAgent.limit_address(conn)

  defp limit_rate(conn, _opts), do: conn

  # Built per request, so the endpoint does not compile against the limiter and
  # the client address modules. Pairing also has its own small budget, since each
  # try spends a guess at a code.
  defp rate_limit(policy, limit) do
    RegentAgentAccess.RateLimit.init(
      policy: policy,
      limit: limit,
      window: 60,
      admit: &Regents.RateLimiter.admit/3,
      key: &RegentsWeb.ClientAddress.key/1
    )
  end
end
